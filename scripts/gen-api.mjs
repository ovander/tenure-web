// Generates src/api/schema.d.ts from api/openapi.json, the OpenAPI document of
// tenure-api (RENT-FE-001 §7), vendored at the commit named in api/SOURCE.
// tenure-api writes Swagger 2.0 (swag), so it is converted to OpenAPI 3 first.
//   node scripts/gen-api.mjs          regenerate
//   node scripts/gen-api.mjs --check  fail if schema.d.ts is not up to date
import { readFile, writeFile } from 'node:fs/promises'
// @ts-expect-error swagger2openapi ships no types
import converter from 'swagger2openapi'
import openapiTS, { astToString } from 'openapi-typescript'

const out = new URL('../src/api/schema.d.ts', import.meta.url)
const swagger = JSON.parse(await readFile(new URL('../api/openapi.json', import.meta.url), 'utf8'))
const { openapi } = await converter.convertObj(swagger, { patch: true, warnOnly: true })
const ast = await openapiTS(openapi, { alphabetize: true })
const text =
  '// Generated by scripts/gen-api.mjs from api/openapi.json (tenure-api). Do not edit.\n' + astToString(ast)

if (process.argv.includes('--check')) {
  const current = await readFile(out, 'utf8').catch(() => '')
  if (current !== text) {
    console.error('src/api/schema.d.ts is out of date: run npm run api')
    process.exit(1)
  }
  console.log('src/api/schema.d.ts is up to date')
} else {
  await writeFile(out, text)
  console.log('wrote src/api/schema.d.ts')
}
